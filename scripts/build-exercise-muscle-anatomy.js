const fs=require("fs");
const path=require("path");
const root=path.resolve(__dirname,"..");
const sides=["front","back"];
const figures={};
for(const side of sides){
  const source=fs.readFileSync(path.join(root,`assets/exercise-library/v2/shared/muscles-${side}.svg`),"utf8");
  const body=source.match(new RegExp(`<g id="body-${side}">([\\s\\S]*?)<\\/g>`));
  if(!body)throw new Error(`Missing body-${side}`);
  const regions={};
  for(const match of source.matchAll(/<g id="muscle-([^"]+)"[^>]*>([\s\S]*?)<\/g>/g))regions[match[1]]=match[2].trim();
  figures[side]={body:body[1].trim(),regions};
}
const output=`/* Generated by scripts/build-exercise-muscle-anatomy.js. Do not edit by hand. */
(function(root,factory){
  const api=factory();
  if(typeof module==="object"&&module.exports)module.exports=api;
  root.ROAD12_EXERCISE_MUSCLE_ANATOMY=api;
})(typeof self!=="undefined"?self:globalThis,function(){
  const PRIMARY="#39FF14";
  const SECONDARY="#FF4FD8";
  const FIGURES=${JSON.stringify(figures)};
  function highlightedPaths(side,region,role){
    const markup=FIGURES[side]?.regions?.[region];
    if(!markup)return "";
    const fill=role==="primary"?PRIMARY:SECONDARY;
    return markup.replace(/<path\\b([^>]*)>/g,(match,attributes)=>{
      const clean=attributes.replace(/\\s(?:fill|style|opacity)="[^"]*"/gi,"");
      return \`<path class="muscle-region \${role}" data-muscle-region="\${region}" fill="\${fill}" style="fill:\${fill}"\${clean}>\`;
    });
  }
  function renderFigure(side,regions){
    const figure=FIGURES[side];
    if(!figure)return "";
    const highlights=[...regions.primary.map(region=>highlightedPaths(side,region,"primary")),...regions.secondary.map(region=>highlightedPaths(side,region,"secondary"))].join("");
    return \`<g class="muscle-anatomy-base" data-anatomy-layer="base">\${figure.body}</g><g class="muscle-anatomy-highlights" data-anatomy-layer="highlights">\${highlights}</g>\`;
  }
  return Object.freeze({PRIMARY,SECONDARY,FIGURES,renderFigure});
});
`;
fs.writeFileSync(path.join(root,"exercise-muscle-anatomy.js"),output);
console.log(`Generated exercise-muscle-anatomy.js with ${Object.keys(figures.front.regions).length} front and ${Object.keys(figures.back.regions).length} back regions.`);
