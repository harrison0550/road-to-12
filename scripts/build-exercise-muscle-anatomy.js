const figures={};
for(const side of ["front","back"]){
  const source=fs.readFileSync(path.join(root,`assets/exercise-library/v2/shared/muscles-${side}.svg`),"utf8");
  const viewBox=source.match(/viewBox="([^"]+)"/)?.[1];
  if(!viewBox)throw new Error(`Missing ${side} viewBox`);
  const paths=[...source.matchAll(/<path\b[\s\S]*?\/>/g)].map((match,index)=>{
    const tag=match[0];
    const id=tag.match(/\bid="([^"]+)"/)?.[1];
    const d=tag.match(/\bd="([^"]+)"/)?.[1];
    if(!id||!d)return null;
    return {domId:`anatomy-${side}-${id}`,id,name:id.replaceAll("_"," "),d,index};
  }).filter(Boolean);
  if(!paths.length)throw new Error(`Missing ${side} anatomy paths`);
  const available=new Set(paths.map(item=>item.id));
  Object.entries(REGION_PATHS[side]).forEach(([region,ids])=>ids.forEach(id=>{
    if(!available.has(id))throw new Error(`Region ${region} references missing ${side} path ${id}`);
  }));
  figures[side]={viewBox,paths};
}

const output=`/* Generated by scripts/build-exercise-muscle-anatomy.js. Do not edit by hand. */
(function(root,factory){
  const api=factory();
  if(typeof module==="object"&&module.exports)module.exports=api;
  root.ROAD12_EXERCISE_MUSCLE_ANATOMY=api;
})(typeof self!=="undefined"?self:globalThis,function(){
  const PRIMARY="#39FF14";
  const SECONDARY="#FF4FD8";
  const NEUTRAL="#737B84";
  const FIGURES=${JSON.stringify(figures)};
  const REGION_PATHS=${JSON.stringify(REGION_PATHS)};
  function selectedPathRoles(side,regions){
    const roles=new Map();
    for(const region of regions.secondary||[])for(const id of REGION_PATHS[side]?.[region]||[])roles.set(id,{region,role:"secondary"});
    for(const region of regions.primary||[])for(const id of REGION_PATHS[side]?.[region]||[])roles.set(id,{region,role:"primary"});
    return roles;
  }
  function renderFigure(side,regions){
    const figure=FIGURES[side];
    if(!figure)return "";
    const roles=selectedPathRoles(side,regions||{});
    return figure.paths.map(path=>{
      const selected=roles.get(path.id);
      const role=selected?.role||"neutral";
      const region=selected?.region||"";
      const fill=role==="primary"?PRIMARY:role==="secondary"?SECONDARY:NEUTRAL;
      const regionAttribute=region?\` data-muscle-region="\${region}"\`:"";
      return \`<path id="\${path.domId}" class="anatomy-path \${role==="neutral"?"anatomy-neutral":\`muscle-region \${role}\`}" data-anatomy-id="\${path.id}"\${regionAttribute} fill="\${fill}" style="fill:\${fill}" d="\${path.d}"/>\`;
    }).join("");
  }
  function viewBox(side){return FIGURES[side]?.viewBox||"0 0 587 1137";}
  return Object.freeze({PRIMARY,SECONDARY,NEUTRAL,FIGURES,REGION_PATHS,renderFigure,viewBox});
});
`;
